-- Initial schema. Written portable SQL: works on H2 (dev) and PostgreSQL (prod).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'CASHIER'))
);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150)  NOT NULL,
    sku                 VARCHAR(50)   NOT NULL UNIQUE,
    barcode             VARCHAR(50)   NOT NULL UNIQUE,
    category_id         BIGINT        NOT NULL,
    cost_price          NUMERIC(12,2) NOT NULL,
    sell_price          NUMERIC(12,2) NOT NULL,
    stock_quantity      INT           NOT NULL DEFAULT 0,
    low_stock_threshold INT           NOT NULL DEFAULT 5,
    active              BOOLEAN       NOT NULL DEFAULT TRUE,
    version             BIGINT        NOT NULL DEFAULT 0,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT chk_product_prices CHECK (cost_price >= 0 AND sell_price >= 0),
    CONSTRAINT chk_product_stock CHECK (stock_quantity >= 0)
);

CREATE TABLE stock_movements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT      NOT NULL,
    movement_type  VARCHAR(20) NOT NULL,
    quantity_delta INT         NOT NULL,
    stock_after    INT         NOT NULL,
    reference      VARCHAR(30),
    user_id        BIGINT      NOT NULL,
    note           VARCHAR(255),
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_movement_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_movement_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_movement_type CHECK (movement_type IN ('RECEIVE', 'CORRECTION', 'DAMAGE', 'SALE', 'VOID_RESTORE'))
);

CREATE TABLE sales (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cashier_id      BIGINT        NOT NULL,
    subtotal        NUMERIC(12,2) NOT NULL,
    discount_type   VARCHAR(10)   NOT NULL,
    discount_value  NUMERIC(12,2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    total           NUMERIC(12,2) NOT NULL,
    payment_method  VARCHAR(10)   NOT NULL,
    cash_tendered   NUMERIC(12,2),
    change_due      NUMERIC(12,2),
    status          VARCHAR(10)   NOT NULL,
    voided_at       TIMESTAMP,
    voided_by_id    BIGINT,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sale_cashier FOREIGN KEY (cashier_id) REFERENCES users (id),
    CONSTRAINT fk_sale_voided_by FOREIGN KEY (voided_by_id) REFERENCES users (id),
    CONSTRAINT chk_sale_discount CHECK (discount_type IN ('NONE', 'AMOUNT', 'PERCENT')),
    CONSTRAINT chk_sale_payment CHECK (payment_method IN ('CASH', 'CARD')),
    CONSTRAINT chk_sale_status CHECK (status IN ('COMPLETED', 'VOIDED'))
);

CREATE TABLE sale_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id      BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_name VARCHAR(150)  NOT NULL,
    product_sku  VARCHAR(50)   NOT NULL,
    unit_price   NUMERIC(12,2) NOT NULL,
    quantity     INT           NOT NULL,
    line_total   NUMERIC(12,2) NOT NULL,
    CONSTRAINT fk_item_sale FOREIGN KEY (sale_id) REFERENCES sales (id),
    CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT chk_item_quantity CHECK (quantity > 0)
);

CREATE INDEX idx_products_name ON products (name);
CREATE INDEX idx_movements_product ON stock_movements (product_id, created_at);
CREATE INDEX idx_sales_created ON sales (created_at);
CREATE INDEX idx_sales_cashier ON sales (cashier_id, created_at);
CREATE INDEX idx_items_sale ON sale_items (sale_id);
CREATE INDEX idx_items_product ON sale_items (product_id, sale_id);
